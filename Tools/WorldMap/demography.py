def main():
    root = sys.argv[1]
    with open(os.path.join(root, "WorldMaps", "cities.json"), encoding="utf-8") as f:
        regions = [region["id"] for region in json.load(f)["regions"]]
    missing = [region for region in regions if region not in POP]
    extra = [region for region in POP if region not in regions]
    bad = [region for region, row in POP.items() if len(row) != len(YEARS)]
    if missing or extra or bad:
        raise SystemExit("缺 %s 多 %s 列数不对 %s" % (missing, extra, bad))
    out = {"_note": "各地区史载人口(万人)，由 Tools/WorldMap/demography.py 生成，勿手改", "years": YEARS, "pop": POP}
    with open(os.path.join(root, "WorldMaps", "demography.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    for i, year in enumerate(YEARS):
        print(year, "合计 %d 万" % sum(row[i] for row in POP.values()))


if __name__ == "__main__":
    main()
